CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    keycloak_id VARCHAR(255) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL,
    is_adult BOOLEAN NOT NULL,
    pocket NUMERIC(12, 2) NOT NULL
);

CREATE TABLE drinks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(255) NOT NULL,
    is_for_adult BOOLEAN NOT NULL
);

CREATE TABLE price_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drink_id BIGINT NOT NULL REFERENCES drinks (id),
    price NUMERIC(12, 2) NOT NULL,
    effective_from TIMESTAMP NOT NULL,
    CONSTRAINT unique_price_record_per_drink_and_effective_date UNIQUE (drink_id, effective_from)
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount INTEGER NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users (id),
    price_record_id BIGINT NOT NULL REFERENCES price_records (id)
);

CREATE INDEX idx_price_records_drink_id ON price_records (drink_id);
CREATE INDEX idx_orders_price_record_id ON orders (price_record_id);
